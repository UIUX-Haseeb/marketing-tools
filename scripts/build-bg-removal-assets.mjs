// Builds the self-hosted resource bundle for @imgly/background-removal into
// public/tools/_shared/bg-removal/ (resources.json + 4 MB chunks named by sha256).
//
//   node scripts/build-bg-removal-assets.mjs <path-to-isnet_quint8-model-file>
//
// The model file comes from the imgly repo (bundle/models/isnet_quint8) or from the
// @imgly/background-removal-data package; the ONNX runtime files come from the installed
// onnxruntime-web (must match the peer version pinned by @imgly/background-removal).
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const CHUNK = 4 * 1024 * 1024;
const OUT = path.resolve("public/tools/_shared/bg-removal");
const ORT = path.resolve("node_modules/onnxruntime-web/dist");
const model = process.argv[2];
if (!model || !fs.existsSync(model)) {
  console.error("Usage: node scripts/build-bg-removal-assets.mjs <isnet_quint8 file>");
  process.exit(1);
}

const entries = [
  { key: "/onnxruntime-web/ort-wasm-simd-threaded.wasm", file: path.join(ORT, "ort-wasm-simd-threaded.wasm"), mime: "application/wasm" },
  { key: "/onnxruntime-web/ort-wasm-simd-threaded.mjs", file: path.join(ORT, "ort-wasm-simd-threaded.mjs"), mime: "text/javascript" },
  { key: "/models/isnet_quint8", file: model, mime: "application/octet-stream" },
];

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const resources = {};
for (const e of entries) {
  const data = fs.readFileSync(e.file);
  const chunks = [];
  for (let offset = 0; offset < data.length; offset += CHUNK) {
    const slice = data.subarray(offset, Math.min(offset + CHUNK, data.length));
    const hash = crypto.createHash("sha256").update(slice).digest("hex");
    fs.writeFileSync(path.join(OUT, hash), slice);
    chunks.push({ hash, name: hash, offsets: [offset, offset + slice.length] });
  }
  resources[e.key] = { chunks, size: data.length, mime: e.mime };
  console.log(`${e.key}  ${(data.length / 1048576).toFixed(1)} MB  ${chunks.length} chunk(s)`);
}
fs.writeFileSync(path.join(OUT, "resources.json"), JSON.stringify(resources, null, 2));
fs.writeFileSync(
  path.join(OUT, "README.md"),
  [
    "Self-hosted model bundle for @imgly/background-removal (see src/tools/README.md).",
    "Generated by `node scripts/build-bg-removal-assets.mjs <isnet_quint8>` — do not edit by hand.",
    "Files named by sha256 are 4 MB chunks of: ISNet quint8 model (42 MB) and onnxruntime-web wasm + loader (12 MB).",
    "",
  ].join("\n"),
);
console.log(`Wrote ${OUT}`);
