export const SAMPLE_COUNT = SAMPLE_DRAFTS.length;

export function sampleDraft(i: number): EventRecord {
  const { art, inDays, days, from, to, ...fields } = SAMPLE_DRAFTS[((i % SAMPLE_COUNT) + SAMPLE_COUNT) % SAMPLE_COUNT];
  const day = (n: number) => {
    const d = new Date();
    d.setDate(d.getDate() + n);
    return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
  };
  const base = blankEvent();
  return {
    ...base,
    ...fields,
    status: "Published",
    slug: slugify(fields.title ?? ""),
    starts: `${day(inDays)}T${from}`,
    ends: `${day(inDays + days - 1)}T${to}`,
    dailyStart: days > 1 ? from : "",
    dailyEnd: days > 1 ? to : "",
    artwork: { ...base.artwork, ...art },
  };
}
