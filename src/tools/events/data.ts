import { NO_ADJUST, type EventArtwork, type EventRecord } from "./types";

export function slugify(s: string) {
  return s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-")
    .slice(0, 80);
}

export function newArtwork(photo = ""): EventArtwork {
  return { design: "a", photo, adjust: { banner: NO_ADJUST, thumb: NO_ADJUST, flyer: NO_ADJUST }, show: { subtitle: true, time: true, location: true }, logo: "" };
}

export function blankEvent(): EventRecord {
  return {
    id: "",
    slug: "",
    title: "",
    subtitle: "",
    types: [],
    status: "Draft",
    audience: "Public",
    shortDescription: "",
    description: "",
    featured: false,
    starts: "",
    ends: "",
    timezone: "Asia/Dubai",
    repeats: [],
    dailyStart: "",
    dailyEnd: "",
    venue: "",
    city: "",
    address1: "",
    address2: "",
    country: "United Arab Emirates",
    mapsUrl: "",
    developer: "",
    project: "",
    community: "",
    online: false,
    registrationUrl: "",
    website: "",
    promoVideo: "",
    livestream: "",
    brochure: "",
    mediaLinks: [],
    artwork: newArtwork(),
    registrationRequired: false,
    capacity: "",
    contactName: "",
    contactPhone: "",
    contactEmail: "",
    created: "",
    createdBy: "",
    updated: "",
    updatedBy: "",
    firstPublished: "",
  };
}

function ev(id: string, e: Partial<EventRecord> & Pick<EventRecord, "title" | "types" | "starts" | "ends">, art?: Partial<EventArtwork>): EventRecord {
  const base = blankEvent();
  return {
    ...base,
    status: "Published",
    ...e,
    id,
    slug: e.slug ?? slugify(e.title),
    artwork: { ...base.artwork, ...art },
    updated: e.updated ?? e.created ?? "",
    updatedBy: e.updatedBy ?? e.createdBy ?? "",
  };
}

